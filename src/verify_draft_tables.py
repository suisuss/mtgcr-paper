"""Draft-vs-artifact gate for the reproduction pipeline.

Regenerates the paper tables via paper_tables.run(check=True) and exits
nonzero unless every emitted cell matches its table block in paper.md.
paper_tables' own CLI always exits 0 (its --check output is
informational); the pipeline needs the loud version - a reproduction
whose regenerated numbers diverge from the printed draft must fail the
run, not print a diff and continue. Runs after the paper_tables stage,
so the tables are already regenerated by the time it compares.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import paper_tables
import manuscript_tables


def _check(mod, label):
    """Run a table module's --check and return (ok, cells, failures)."""
    summary = mod.run(check=True)
    check = summary.get("check", {})
    bad = [t for t, v in check.get("per_table", {}).items()
           if v.get("status") != "OK"]
    ok, cells = check.get("total_ok", 0), check.get("total_cells", -1)
    failures = []
    if bad:
        failures.append(f"{label}: tables not matching {bad}")
    if ok != cells or cells <= 0:
        failures.append(f"{label}: {ok}/{cells} cells match")
    if summary.get("discrepancies"):
        failures.append(f"{label}: narrative discrepancies "
                        f"{summary['discrepancies']}")
    return ok, cells, failures


def main(argv=None):
    total_ok = total_cells = 0
    failures = []
    # spike-round tables gate against reproduction_record.md; manuscript
    # tables gate against paper.md.
    for mod, label in ((paper_tables, "reproduction_record.md"),
                       (manuscript_tables, "paper.md")):
        ok, cells, f = _check(mod, label)
        total_ok += ok
        total_cells += cells
        failures += f
    if failures:
        for f in failures:
            print(f"[verify_draft_tables] FAILED: {f}", file=sys.stderr)
        return 1
    print(f"[verify_draft_tables] OK: {total_ok}/{total_cells} cells match "
          "(spike record + manuscript)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
