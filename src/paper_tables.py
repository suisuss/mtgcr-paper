"""Table generator for the spike-round draft (draft-vs-artifact gate).

Regenerates paper/tables/*.md from data/results/experiments and (with
--check) verifies each regenerated table matches the block after its
`<!-- table: <name> -->` marker in paper.md.

    python paper_tables.py           regenerate paper/tables/*.md
    python paper_tables.py --check   regenerate + verify against paper.md
"""
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RESULTS = REPO / "data" / "results" / "experiments"
TABLES = REPO / "paper" / "tables"
DRAFT = REPO / "paper" / "reproduction_record.md"

CORPORA = ["sgd", "mwoz"]


def _load(name):
    return json.loads((RESULTS / f"{name}.json").read_text())


def _fmt_auc(v):
    return f"{v:.3f}" if v is not None else "-"


def t01_zone_lift():
    header = ("<!-- generated by paper_tables.py from: "
              "spike1_zone_{sgd,mwoz}.json -->")
    rows = ["| Corpus | Bad/good convs | Base rate | Max lift [boot 95% CI] "
            "| High-risk clusters | First-entry tau (median) | Early share |",
            "|---|---|---|---|---|---|---|"]
    for c in CORPORA:
        r = _load(f"spike1_zone_{c}")
        lead = r["lead_time"]
        ft = (f"{lead['median_first_tau']:.2f}"
              if lead["median_first_tau"] is not None else "-")
        es = (f"{lead['early_share']:.2f}"
              if lead["early_share"] is not None else "-")
        rows.append(
            f"| {c.upper()} | {r['n_bad']}/{r['n_good']} "
            f"| {r['base_rate']:.3f} "
            f"| {r['max_lift']:.2f} [{r['max_lift_boot_ci'][0]:.2f}, "
            f"{r['max_lift_boot_ci'][1]:.2f}] "
            f"| {r['n_highrisk']} | {ft} | {es} |")
    return header, rows


