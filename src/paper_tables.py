def _extract_draft_table(name):
    text = DRAFT.read_text()
    m = re.search(rf"<!--\s*table:\s*{re.escape(name)}\s*-->\n"
                  r"((?:\|.*\n?)+)", text)
    if not m:
        return None
    return [ln for ln in m.group(1).splitlines() if ln.strip()]


def run(check=False):
    TABLES.mkdir(parents=True, exist_ok=True)
    summary = {"tables_written": [], "discrepancies": []}
    per_table = {}
    total_ok = total_cells = 0
    for name, builder in BUILDERS.items():
        header, rows = builder()
        (TABLES / f"{name}.md").write_text(header + "\n"
                                           + "\n".join(rows) + "\n")
        summary["tables_written"].append(name)
        if check:
            draft_rows = _extract_draft_table(name)
            if draft_rows is None:
                per_table[name] = {"status": "NOT FOUND"}
                continue
            ok = sum(1 for a, b in zip(rows, draft_rows) if a == b)
            cells = max(len(rows), len(draft_rows))
            per_table[name] = {"status": "OK" if ok == cells else "MISMATCH",
                               "ok": ok, "cells": cells}
            total_ok += ok
            total_cells += cells
            if ok != cells:
                summary["discrepancies"].append(name)
    if check:
        summary["check"] = {"per_table": per_table, "total_ok": total_ok,
                            "total_cells": total_cells}
    return summary


def main(argv=None):
    check = bool(argv and "--check" in argv) or "--check" in sys.argv[1:]
    summary = run(check=check)
    if check:
        print(json.dumps(summary["check"], indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
